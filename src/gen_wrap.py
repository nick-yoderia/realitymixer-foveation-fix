"""Generate pass-through wrappers for two OpenVR interfaces, as Reality Mixer uses them.

    python gen_wrap.py openvr-1.26.7/openvr.h

Reads `class IVROverlay` (IVROverlay_027) and `class IVRSystem` (IVRSystem_022) from the
OpenVR 1.26.7 header and writes wrap_overlay.h / wrap_system.h: every method calls
rmfix::Tick() and forwards to the real interface. SetOverlayTexture and GetOverlayTexture
also report successful calls to rmfix (see rmfix.cpp).
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8", errors="replace").read()

def methods(cls):
    body = re.search(r"class %s\s*\{\s*public:(.*?)\n\t\};" % cls, src, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    for ret_name, params in re.findall(r"virtual\s+(.*?)\s*\(\s*(.*?)\s*\)\s*=\s*0\s*;", body, re.S):
        ret, name = re.match(r"(.*?)(\w+)$", " ".join(ret_name.split())).groups()
        ps = []
        for p in [x.strip() for x in " ".join(params.split()).split(",") if x.strip()]:
            p = re.sub(r"\s*=\s*[^,]+$", "", p)  # default arguments
            t, n = re.match(r"(.*?)(\w+)$", p).groups()
            ps.append((t.strip(), n))
        yield ret.strip(), name, ps

HOOKS = {  # method -> statement run after a successful call (r == 0)
    "SetOverlayTexture": "rmfix::OnSetTexture(ulOverlayHandle, pTexture);",
    "GetOverlayTexture": "rmfix::OnGetTexture(ulOverlayHandle, pNativeTextureHandle, pAPIType);",
}

def wrap(cls, wrapper, out):
    lines = ["// Generated by gen_wrap.py from the OpenVR 1.26.7 header. Do not edit.",
             "class %s : public vr::%s {" % (wrapper, cls), "public:", "\tvr::%s *real;" % cls]
    n = 0
    for ret, name, ps in methods(cls):
        plist = ", ".join("%s %s" % p for p in ps)
        args = ", ".join(n_ for _, n_ in ps)
        call = "real->%s(%s)" % (name, args)
        if name in HOOKS:
            body = "rmfix::Tick(); auto r = %s; if (!r) %s return r;" % (call, HOOKS[name])
        elif ret == "void":
            body = "rmfix::Tick(); %s;" % call
        else:
            body = "rmfix::Tick(); return %s;" % call
        lines.append("\t%s %s(%s) override { %s }" % (ret, name, plist, body))
        n += 1
    lines.append("};")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(out, n, "methods")

wrap("IVROverlay", "WrapOverlay", "wrap_overlay.h")
wrap("IVRSystem", "WrapSystem", "wrap_system.h")
